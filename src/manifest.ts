import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { parse, stringify } from "yaml";
import { toLf } from "./files.js";

export interface DocEntryManifest {
  /** Git commit the doc was last verified against; `update` diffs from here. */
  commit?: string;
  stamped: string;
  /** Source file → short sha256 of its content when the doc was stamped. */
  sources: Record<string, string>;
}

export interface Manifest {
  version: 1;
  docs: Record<string, DocEntryManifest>;
}

export const manifestPath = (root: string, contextDir: string) => join(root, contextDir, "manifest.yaml");

export function loadManifest(root: string, contextDir: string): Manifest {
  const path = manifestPath(root, contextDir);
  if (!existsSync(path)) return { version: 1, docs: {} };
  const data = parse(readFileSync(path, "utf8")) as Partial<Manifest> | null;
  return { version: 1, docs: data?.docs ?? {} };
}

export function saveManifest(root: string, contextDir: string, manifest: Manifest): void {
  const path = manifestPath(root, contextDir);
  mkdirSync(dirname(path), { recursive: true });
  const sorted: Manifest = {
    version: 1,
    docs: Object.fromEntries(Object.entries(manifest.docs).sort(([a], [b]) => a.localeCompare(b))),
  };
  writeFileSync(path, `# Generated by easy-repo-context. Doc → source hashes; \`easy-repo-context check\` compares against these.\n${stringify(sorted)}`);
}

export function hashFile(root: string, path: string): string | undefined {
  try {
    // Hash text with LF endings: a CRLF checkout on Windows must not look "changed" to a Linux teammate.
    const bytes = readFileSync(join(root, path));
    const content = bytes.includes(0) ? bytes : toLf(bytes.toString("utf8"));
    return createHash("sha256").update(content).digest("hex").slice(0, 16);
  } catch {
    return undefined;
  }
}

export function headCommit(root: string): string | undefined {
  try {
    return execFileSync("git", ["rev-parse", "--short=12", "HEAD"], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return undefined;
  }
}
